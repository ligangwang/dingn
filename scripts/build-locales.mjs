#!/usr/bin/env node
// Language packs. Every language other than English (dingn's own language,
// at the original URLs) is one file in locales/: its name, its HTML language
// code, the URL prefix its pages live under, and its text:
//
//   { "name": "Español", "lang": "es", "path": "/es",
//     "strings": { "<English text>": "<translation>", … } }
//
// Adding a language is adding a pack. This script, run before every build
// and dev server (npm's prebuild / predev) and checked by the tests:
//   - checks each pack (see checkPack),
//   - writes src/data/locales.gen.mjs, the list of languages (no text), which
//     the website and the server share, and
//   - copies each pack's text to public/locales/<lang>.json, which the
//     browser fetches when a player switches language.
// A page gets only its own language's text (src/app/[lang]/layout.tsx).
import { mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

/** Open Graph locale codes for languages whose region isn't the language code. */
const OG = { ja: "ja_JP", ko: "ko_KR", es: "es_ES", id: "id_ID", en: "en_US" };
export const ogLocale = (lang) => OG[lang] ?? lang.replace("-", "_");

/** Problems with a pack, as messages (none for a good pack). */
export function checkPack(pack, file = "pack") {
  const problems = [];
  const at = (m) => problems.push(`${file}: ${m}`);
  if (typeof pack?.name !== "string" || !pack.name) at("needs a name");
  if (typeof pack?.lang !== "string" || !/^[a-z]{2,3}(-[A-Z]{2})?$/.test(pack.lang))
    at('needs a lang such as "es" or "pt-BR"');
  if (typeof pack?.path !== "string" || !/^\/[a-z]{2,3}$/.test(pack.path))
    at('needs a path such as "/es"');
  if (!pack?.strings || typeof pack.strings !== "object") at("needs strings");
  else
    for (const [key, value] of Object.entries(pack.strings)) {
      if (typeof value !== "string" || !value.trim()) at(`empty: ${key}`);
      else {
        const holders = (s) => (s.match(/\{\d+\}/g) ?? []).sort().join(",");
        if (holders(key) !== holders(value))
          at(`placeholders differ: ${key} → ${value}`);
      }
    }
  return problems;
}

/** Every pack in `dir`, checked, English first (it has no pack). */
export function readPacks(dir) {
  const packs = readdirSync(dir)
    .filter((f) => f.endsWith(".json"))
    .sort()
    .map((f) => {
      const pack = JSON.parse(readFileSync(path.join(dir, f), "utf8"));
      const problems = checkPack(pack, f);
      if (problems.length) throw new Error(problems.join("\n"));
      if (f !== `${pack.lang}.json`) throw new Error(`${f}: name it ${pack.lang}.json`);
      return pack;
    });
  const paths = packs.map((p) => p.path);
  if (new Set(paths).size !== paths.length) throw new Error("two packs share a path");
  return packs;
}

/** The list of languages for src/data/locales.gen.mjs. */
export function localeList(packs) {
  return [
    { lang: "en", name: "English", path: "", og: ogLocale("en") },
    ...packs.map((p) => ({
      lang: p.lang,
      name: p.name,
      path: p.path,
      og: ogLocale(p.lang),
    })),
  ];
}

export const generated = (list) =>
  `// Generated by scripts/build-locales.mjs from locales/*.json. Do not edit.\n` +
  `/** Every language dingn speaks, English first: its code, name, URL prefix and Open Graph locale. */\n` +
  `export const LOCALES = ${JSON.stringify(list, null, 2)};\n`;

export function buildLocales(repo) {
  const packs = readPacks(path.join(repo, "locales"));
  writeFileSync(
    path.join(repo, "src", "data", "locales.gen.mjs"),
    generated(localeList(packs)),
  );
  const out = path.join(repo, "public", "locales");
  mkdirSync(out, { recursive: true });
  for (const pack of packs)
    writeFileSync(path.join(out, `${pack.lang}.json`), JSON.stringify(pack.strings));
  return packs;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const packs = buildLocales(path.join(path.dirname(fileURLToPath(import.meta.url)), ".."));
  console.log(`languages: en, ${packs.map((p) => p.lang).join(", ")}`);
}
